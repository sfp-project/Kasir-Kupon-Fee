function isoOffset(daysAgo: number, hours: number, minutes: number): string {
  const now = new Date();
  const target = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() - daysAgo,
    hours,
    minutes,
    0,
    0,
  );
  // If computed time is in the future for today, clamp to a few minutes ago so timestamps feel authentic
  if (daysAgo === 0 && target.getTime() > now.getTime()) {
    return new Date(now.getTime() - (minutes + 5) * 60_000).toISOString();
  }
  return target.toISOString();
}

function dateCode(daysAgo: number): string {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  const yy = String(d.getFullYear()).slice(-2);
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  const dd = String(d.getDate()).padStart(2, '0');
  return `${yy}${mm}${dd}`;
}

